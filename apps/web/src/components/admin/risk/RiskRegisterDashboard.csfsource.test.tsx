async function loaded(): Promise<void> {
  render(<RiskRegisterDashboard />);
  await waitFor(() =>
    expect(
      screen.getByRole("heading", { name: "Risk Register" }),
    ).toBeInTheDocument(),
  );
}

describe("RiskRegisterDashboard states the CSF source (#474 D')", () => {
  beforeEach(() => {
    vi.clearAllMocks();
    getActiveClientId.mockResolvedValue("c1");
    getClientName.mockResolvedValue("Client");
    fetchRiskGate.mockResolvedValue(gate());
  });

  it("renders the API's sentence", async () => {
    fetchRiskRegisterLatest.mockResolvedValue(
      register({ csf_source_note: NOTE }),
    );
    await loaded();
    expect(screen.getByTestId("risk-csf-source")).toHaveTextContent(NOTE);
  });

  it("renders nothing when the register has no CSF findings", async () => {
    fetchRiskRegisterLatest.mockResolvedValue(
      register({ csf_source_note: null }),
    );
    await loaded();
    expect(screen.getByText("Credential theft")).toBeInTheDocument();
    expect(screen.queryByTestId("risk-csf-source")).toBeNull();
  });
});
