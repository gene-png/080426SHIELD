async function loaded(): Promise<void> {
  render(<RiskRegisterDashboard />);
  await waitFor(() =>
    expect(
      screen.getByRole("heading", { name: "Risk Register" }),
    ).toBeInTheDocument(),
  );
}

describe("RiskRegisterDashboard baseline (#474)", () => {
  beforeEach(() => {
    vi.clearAllMocks();
    getActiveClientId.mockResolvedValue("c1");
    getClientName.mockResolvedValue("Client");
    fetchRiskGate.mockResolvedValue(gate());
  });

  it("states each service's target", async () => {
    fetchRiskRegisterLatest.mockResolvedValue(
      register({
        targets: [
          {
            service: "zt",
            target: 3,
            source: "default",
            origin: "live_at_generate",
          },
        ],
        targets_recorded: true,
      }),
    );
    await loaded();
    expect(screen.getByTestId("risk-targets-used").textContent).toBe(
      "Zero Trust findings are measured against target stage 3, SHIELD's default: no engagement target was set.",
    );
  });

  it("says not recorded for a register that predates the record", async () => {
    fetchRiskRegisterLatest.mockResolvedValue(register());
    await loaded();
    expect(screen.getByTestId("risk-targets-used").textContent).toBe(
      "The targets these findings were measured against were not recorded for this register.",
    );
  });
});
